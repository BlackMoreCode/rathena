[CmdletBinding(SupportsShouldProcess)]
param(
    [Parameter(Mandatory=$true)]
    [ValidateSet('Local','Production')][string]$Profile,
    [string]$PublicAddress,
    [string]$ServerRoot = (Split-Path $PSScriptRoot -Parent)
)
$ErrorActionPreference = 'Stop'
$ServerRoot = (Resolve-Path -LiteralPath $ServerRoot).Path
if (-not (Test-Path -LiteralPath (Join-Path $ServerRoot 'conf/map_athena.conf'))) {
    throw 'ServerRoot must contain the rAthena conf directory.'
}
if ($Profile -eq 'Production' -and
    ([string]::IsNullOrWhiteSpace($PublicAddress) -or
     [Uri]::CheckHostName($PublicAddress) -eq [UriHostNameType]::Unknown)) {
    throw 'Production requires -PublicAddress with an IP address or host name.'
}
$bindAddress = if ($Profile -eq 'Local') { '127.0.0.1' } else { '0.0.0.0' }
$advertisedAddress = if ($Profile -eq 'Local') { '127.0.0.1' } else { $PublicAddress }
$settings = [ordered]@{
    login = "bind_ip: $bindAddress`nlogin_port: 6900`n"
    char = "login_ip: 127.0.0.1`nlogin_port: 6900`nbind_ip: $bindAddress`nchar_ip: $advertisedAddress`nchar_port: 6121`n"
    map = "char_ip: 127.0.0.1`nchar_port: 6121`nbind_ip: $bindAddress`nmap_ip: $advertisedAddress`nmap_port: 5121`n"
    web = "bind_ip: $bindAddress`nweb_port: 8889`n"
}
if (-not $PSCmdlet.ShouldProcess($ServerRoot, "Set $Profile machine network overrides (no DB or credentials changes)")) { return }
$importRoot = Join-Path $ServerRoot 'conf/import'
$networkRoot = Join-Path $importRoot 'cope-network'
New-Item -ItemType Directory -Path $networkRoot -Force | Out-Null
$utf8 = New-Object System.Text.UTF8Encoding($false)
foreach ($service in $settings.Keys) {
    $file = Join-Path $networkRoot ($service + '.conf')
    [IO.File]::WriteAllText($file, "// Generated by Set-CopeNetwork.ps1. Machine-local, ignored by Git.`n" + $settings[$service], $utf8)
    $importFile = Join-Path $importRoot ($service + '_conf.txt')
    $text = if (Test-Path -LiteralPath $importFile) { [IO.File]::ReadAllText($importFile) } else { '' }
    $line = "import: conf/import/cope-network/$service.conf"
    # Remove only this generated include, then put it last so overrides win.
    $pattern = '(?m)^\s*import:\s*conf/import/cope-network/' + $service + '\.conf\s*\r?$'
    $text = [regex]::Replace($text, $pattern, '').TrimEnd()
    [IO.File]::WriteAllText($importFile, $text + "`n`n" + $line + "`n", $utf8)
}
Write-Output "Configured $Profile network overrides in conf/import/cope-network. Restart servers to apply."
Write-Output 'Database credentials, firewall rules and router forwarding were not changed.'
